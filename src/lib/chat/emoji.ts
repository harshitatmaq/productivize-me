/** Flat lookup built from the groups above — the groups stay the source of truth. */
export const EMOJI_MAP: Record<string, string> = Object.fromEntries(
  EMOJI_GROUPS.flatMap((group) => group.entries)
);

export const EMOJI_COUNT = Object.keys(EMOJI_MAP).length;

/**
 * Shortcode names are deliberately narrow: lowercase letters, digits and a few
 * separators. That keeps `12:30:45` and `https://…` from being mistaken for
 * shortcodes, and a replacement only ever happens on an exact map hit anyway.
 */
const SHORTCODE = /:([a-z0-9_+-]{1,24}):/gi;
const TRAILING_SHORTCODE = /:([a-z0-9_+-]{1,24}):$/i;

/** Expands every shortcode in the text. Used on send and for pasted content. */
export function expandEmoji(text: string): string {
  return text.replace(SHORTCODE, (match, name: string) => {
    const emoji = EMOJI_MAP[name.toLowerCase()];
    return emoji ?? match;
  });
}

/**
 * Expands only a shortcode that ends exactly at the cursor — the one just
 * completed by typing its closing colon.
 *
 * Scoping it to the cursor is what makes live expansion feel safe: editing text
 * earlier in the line never rewrites something you are not looking at, and the
 * returned cursor keeps the caret where the typist expects it.
 */
export function expandEmojiAtCursor(
  text: string,
  cursor: number
): { text: string; cursor: number } {
  const before = text.slice(0, cursor);
  const match = before.match(TRAILING_SHORTCODE);
  if (!match) return { text, cursor };

  const emoji = EMOJI_MAP[match[1].toLowerCase()];
  if (!emoji) return { text, cursor };

  const start = cursor - match[0].length;
  const next = text.slice(0, start) + emoji + text.slice(cursor);
  return { text: next, cursor: start + emoji.length };
}
